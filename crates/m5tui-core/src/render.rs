/// Look up the 6 column bytes for a glyph byte. Returns the space-glyph bytes
/// for any byte outside the printable ASCII range.
#[inline]
pub(crate) fn glyph_cols(glyph: u8) -> [u8; GLYPH_BYTES] {
    if (32..=127).contains(&glyph) {
        let idx = (glyph - 32) as usize * GLYPH_BYTES;
        let mut out = [0u8; GLYPH_BYTES];
        out.copy_from_slice(&ATLAS[idx..idx + GLYPH_BYTES]);
        out
    } else {
        [0u8; GLYPH_BYTES]
    }
}

/// Render the current `AppState` into a fresh `Frame`. The title is drawn
/// centred on row 8 in cyan on black. Anything that doesn't fit is clipped.
pub fn render(state: &AppState) -> Frame {
    let mut frame = Frame::new_solid(BLACK);
    let text = state.title.as_bytes();
    let len = text.len().min(COLS);
    let start_col = (COLS - len) / 2;
    let start_row = ROWS / 2;

    for (i, &b) in text.iter().take(len).enumerate() {
        frame.cells[start_row][start_col + i] = Cell {
            glyph: b,
            fg: CYAN,
            bg: BLACK,
            attrs: 0,
        };
    }

    frame
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn atlas_has_96_glyphs_of_6_bytes() {
        assert_eq!(ATLAS.len(), 96 * 6);
        assert_eq!(ATLAS_LEN * GLYPH_BYTES, ATLAS.len());
    }

    #[test]
    fn atlas_space_is_blank() {
        let cols = glyph_cols(b' ');
        assert!(cols.iter().all(|&b| b == 0));
    }

    #[test]
    fn atlas_m_has_pixel_at_col2_row4() {
        // The sim cockpit test asserts the (col=2, row=4) pixel of 'm' is
        // set, so verify the bit pattern here.
        let cols = glyph_cols(b'm');
        assert_eq!(cols[5], 0x00, "padding column should be zero");
        let col2 = cols[2];
        assert_ne!(
            col2 & (1 << 4),
            0,
            "expected bit 4 (row 4) of col 2 to be set in 'm', got 0x{col2:02X}",
        );
    }

    #[test]
    fn render_writes_title_cyan_on_black() {
        let f = render(&AppState::default());
        // "m5Tui v0.1.0" is 12 chars; (40 - 12) / 2 = 14, ROWS / 2 = 8.
        let (start_col, start_row) = (14, 8);
        // First char of the default title is 'm'.
        let cell = f.cells[start_row][start_col];
        assert_eq!(cell.glyph, b'm');
        assert_eq!(cell.fg, CYAN);
        assert_eq!(cell.bg, BLACK);
    }

    #[test]
    fn render_centers_short_title() {
        let s = AppState {
            title: "HI".into(),
            frame_count: 0,
            should_quit: false,
        };
        let f = render(&s);
        // "HI" is 2 chars, so start_col = (40 - 2) / 2 = 19, start_row = 8.
        assert_eq!(f.cells[8][19].glyph, b'H');
        assert_eq!(f.cells[8][20].glyph, b'I');
        // Cell just before H is still blank.
        assert_eq!(f.cells[8][18].glyph, b' ');
    }
}
